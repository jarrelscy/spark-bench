#!/usr/bin/env python3
"""Render the verified leaderboard from spark_bench.csv into the Obsidian vault.

Single source of truth: results/spark_bench.csv. Every number in the output
carries its run_id. Agents must quote THIS note (or the CSV), never hand-copied
tables. Regenerated by cron via ~/obsidian-vault/.scripts/vault_maintain.sh.
"""
import csv, re, datetime, collections

CSV = "/home/raulwesche/projects/spark-bench/results/spark_bench.csv"
OUT = "/home/raulwesche/obsidian-vault/Projects/Leaderboard (AUTO).md"

SUMMARY = ["truescore", "capability_score", "calibration", "reliability",
           "operational_score", "quality", "efficiency", "responsiveness"]

def base_of(run_id):
    return re.sub(r"-\d{8}-\d{6}$", "", run_id)

def model_of(base):
    m = re.sub(r"-(thinkON|thinkOFF|native-auto).*$", "", base)
    return m

def think_of(base):
    if "thinkON" in base: return "ON"
    if "thinkOFF" in base: return "OFF"
    return "auto"

runs = collections.defaultdict(lambda: {"metrics": {}, "tier": "", "ts": "",
                                        "topology": "", "spec": "", "ss": [], "agg": [], "ps": []})
with open(CSV) as f:
    for r in csv.DictReader(f):
        run = runs[r["run_id"]]
        run["tier"] = r["tier"]; run["ts"] = max(run["ts"], r["timestamp"])
        if r["topology"] and r["topology"] not in ("unknown",): run["topology"] = r["topology"]
        if r["spec_decode"] and r["spec_decode"] != "na": run["spec"] = r["spec_decode"]
        if r["tier"] == "eval" and r["metric"] in SUMMARY:
            run["metrics"][r["metric"]] = r["value"]
        if r["tier"] == "tier2":
            if r["workload"] == "single_stream" and r["metric"] == "decode_tps":
                run["ss"].append(float(r["value"]))
            if r["workload"] == "concurrency" and r["metric"] == "agg_decode_tps":
                run["agg"].append(float(r["value"]))
            if r["workload"] == "concurrency" and r["metric"] == "per_stream_tps":
                run["ps"].append(float(r["value"]))

# latest run per base label
latest = {}
for rid, run in runs.items():
    b = base_of(rid)
    if b not in latest or run["ts"] > runs[latest[b]]["ts"]:
        latest[b] = rid

now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
L = []
L.append("---")
L.append("tags: [leaderboard, auto-generated, spark-bench, truescore]")
L.append(f"generated: {now}")
L.append("---")
L.append("")
L.append("# Leaderboard (AUTO)")
L.append("")
L.append(f"> ⚠️ **AUTO-GENERATED {now} from `spark_bench.csv` — do not hand-edit.**")
L.append("> Every row carries its run_id (traceable to the CSV). Agents: quote numbers")
L.append("> ONLY from this note or the CSV itself. If a number is not here, it is **not measured**.")
L.append("")

# ---- v6.1 board ----
L.append("## TrueScore v6.1 (think-OFF unless marked)")
L.append("")
L.append("| # | Model | Think | TrueScore | Cap | Cal | Rel | Topology | Spec | run_id |")
L.append("|---|---|---|---:|---:|---:|---:|---|---|---|")
rows = []
for b, rid in latest.items():
    run = runs[rid]
    if run["tier"] == "eval" and "v6.1" in b and "truescore" in run["metrics"]:
        m = run["metrics"]
        rows.append((float(m["truescore"]), model_of(b), think_of(b),
                     m.get("capability_score", ""), m.get("calibration", ""),
                     m.get("reliability", ""), run["topology"], run["spec"], rid))
for i, (ts, mod, th, cap, cal, rel, topo, spec, rid) in enumerate(
        sorted(rows, key=lambda x: -x[0]), 1):
    L.append(f"| {i} | {mod} | {th} | **{ts:.1f}** | {cap} | {cal} | {rel} | {topo} | {spec} | `{rid}` |")
L.append("")

# ---- throughput board ----
L.append("## Serving throughput (tier2, measured)")
L.append("")
L.append("| Model / config | Single-stream tok/s | Aggregate tok/s (rising concurrency) | Spec | run_id |")
L.append("|---|---|---|---|---|")
for b, rid in sorted(latest.items()):
    run = runs[rid]
    if run["tier"] == "tier2" and (run["ss"] or run["agg"]):
        ss = " / ".join(f"{v:.1f}" for v in sorted(run["ss"])) or "—"
        agg = " → ".join(f"{v:.0f}" for v in sorted(run["agg"])) or "—"
        L.append(f"| {model_of(b)} | {ss} | {agg} | {run['spec']} | `{rid}` |")
L.append("")

# ---- older suites pointer ----
n_other = sum(1 for b, rid in latest.items()
              if runs[rid]["tier"] == "eval" and "v6.1" not in b and "truescore" in runs[rid]["metrics"])
L.append(f"*{n_other} runs from earlier suites (v2/v5c…) are in the CSV — scores across suite versions are NOT comparable.*")
L.append("")
L.append("Source: `~/projects/spark-bench/results/spark_bench.csv` · Renderer: `render_leaderboard.py`")
L.append("")

with open(OUT, "w") as f:
    f.write("\n".join(L))
print(f"wrote {OUT}: {len(rows)} v6.1 rows")
