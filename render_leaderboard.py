#!/usr/bin/env python3
"""Render the verified leaderboard from spark_bench.csv into the Obsidian vault.

Single source of truth: results/spark_bench.csv. Every number in the output
carries its run_id. Agents must quote THIS note (or the CSV), never hand-copied
tables. Regenerated by cron via ~/obsidian-vault/.scripts/vault_maintain.sh.

Integrity rules (2026-07-04):
  - scores are read VERBATIM from the CSV — this script never recomputes them
  - runs whose provenance row says quarantine != clean are EXCLUDED from the
    boards and listed separately with the reason
  - each row shows the grader git hash that produced it (blank = legacy run,
    pre-provenance; treat with suspicion)
  - one board per suite version — scores across versions are NOT comparable
"""
import csv, re, datetime, collections

CSV = "/home/raulwesche/projects/spark-bench/results/spark_bench.csv"
OUT = "/home/raulwesche/obsidian-vault/Projects/Leaderboard (AUTO).md"

SUMMARY = ["truescore", "capability_score", "calibration", "reliability",
           "operational_score", "quality", "efficiency", "responsiveness"]

def base_of(run_id):
    return re.sub(r"-\d{8}-\d{6}$", "", run_id)

def model_of(base):
    return re.sub(r"-(thinkON|thinkOFF|native-auto).*$", "", base)

def think_of(base):
    if "thinkON" in base: return "ON"
    if "thinkOFF" in base: return "OFF"
    return "auto"

def suite_of(base):
    m = re.search(r"-(v\d+(?:\.\d+)?[a-z]?)-", base + "-")
    return m.group(1) if m else "?"

def ver_key(v):
    m = re.match(r"v(\d+)(?:\.(\d+))?([a-z]?)$", v)
    if not m:
        return (0, 0, "")
    return (int(m.group(1)), int(m.group(2) or 0), m.group(3) or "")

runs = collections.defaultdict(lambda: {"metrics": {}, "prov": {}, "has_eval": False,
                                        "ts": "", "topology": "", "spec": "",
                                        "ss": [], "agg": [], "ps": []})
with open(CSV) as f:
    for r in csv.DictReader(f):
        run = runs[r["run_id"]]
        run["ts"] = max(run["ts"], r["timestamp"])
        if r["topology"] and r["topology"] not in ("unknown",): run["topology"] = r["topology"]
        if r["spec_decode"] and r["spec_decode"] != "na": run["spec"] = r["spec_decode"]
        if r["tier"] == "eval":
            run["has_eval"] = True
            if r["workload"] == "provenance":
                run["prov"][r["metric"]] = r["value"]
            elif r["metric"] in SUMMARY:
                run["metrics"][r["metric"]] = r["value"]
        if r["tier"] == "tier2":
            if r["workload"] == "single_stream" and r["metric"] == "decode_tps":
                run["ss"].append(float(r["value"]))
            if r["workload"] == "concurrency" and r["metric"] == "agg_decode_tps":
                run["agg"].append(float(r["value"]))
            if r["workload"] == "concurrency" and r["metric"] == "per_stream_tps":
                run["ps"].append(float(r["value"]))

# Retro-quarantine: runs from before provenance stamping that are KNOWN to have
# ridden the v6.1 auto-pass grader build (agentic domain_quality exactly 100.0
# flat — verified in the CSV 2026-07-04). They stay visible in the quarantine
# section but never rank. Remove an entry only after a regrade replaces it.
KNOWN_BAD = {
    "Gemma-4-26B-A4B-it-thinkOFF-64scen-v6.1-1Spark-20260702-082117":
        "v6.1 auto-pass build (agentic flat 100.0); superseded by v6.2 REGRADE 89.1",
    "MoA-3Spark-gemma26+qwen35-deepseekHead-thinkOFF-64scen-v6.1-20260703-150133":
        "v6.1 auto-pass build (agentic flat 100.0); needs v6.2+ regrade",
}


def quarantined(run):
    q = run["prov"].get("quarantine", "")
    return q not in ("", "clean")

def aborted(run):
    return "aborted" in run["prov"]

# latest CLEAN run per base label for the boards; quarantined/aborted listed apart
latest = {}
quarantine_list = []
for rid, run in runs.items():
    if not run["has_eval"] and not (run["ss"] or run["agg"]):
        continue
    if aborted(run):
        continue  # preflight/gate aborts never scored anything
    b = base_of(rid)
    if rid in KNOWN_BAD:
        quarantine_list.append((rid, KNOWN_BAD[rid]))
        continue
    if run["has_eval"] and quarantined(run):
        quarantine_list.append((rid, run["prov"].get("quarantine", "?")))
        continue
    if b not in latest or run["ts"] > runs[latest[b]]["ts"]:
        latest[b] = rid

now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
L = []
L.append("---")
L.append("tags: [leaderboard, auto-generated, spark-bench, truescore]")
L.append(f"generated: {now}")
L.append("---")
L.append("")
L.append("# Leaderboard (AUTO)")
L.append("")
L.append(f"> ⚠️ **AUTO-GENERATED {now} from `spark_bench.csv` — do not hand-edit.**")
L.append("> Every row carries its run_id (traceable to the CSV). Agents: quote numbers")
L.append("> ONLY from this note or the CSV itself. If a number is not here, it is **not measured**.")
L.append("> `grader` = git hash of the grader that scored the run; blank = legacy run")
L.append("> from before provenance stamping — treat legacy numbers with suspicion.")
L.append("")

# ---- one board per v6+ suite version, newest first ----
eval_latest = [(b, rid) for b, rid in latest.items()
               if runs[rid]["has_eval"] and "truescore" in runs[rid]["metrics"]]
by_suite = collections.defaultdict(list)
for b, rid in eval_latest:
    s = suite_of(b)
    if ver_key(s) >= (6, 0, ""):
        by_suite[s].append((b, rid))

n_rows_total = 0
for suite in sorted(by_suite, key=ver_key, reverse=True):
    L.append(f"## TrueScore {suite} (think-OFF unless marked)")
    L.append("")
    L.append("| # | Model | Think | TrueScore | Cap | Cal | Rel | Topology | Spec | grader | run_id |")
    L.append("|---|---|---|---:|---:|---:|---:|---|---|---|---|")
    rows = []
    for b, rid in by_suite[suite]:
        run = runs[rid]
        m = run["metrics"]
        rows.append((float(m["truescore"]), model_of(b), think_of(b),
                     m.get("capability_score", ""), m.get("calibration", ""),
                     m.get("reliability", ""), run["topology"], run["spec"],
                     run["prov"].get("grader_git", ""), rid))
    for i, (ts, mod, th, cap, cal, rel, topo, spec, gg, rid) in enumerate(
            sorted(rows, key=lambda x: -x[0]), 1):
        L.append(f"| {i} | {mod} | {th} | **{ts:.1f}** | {cap} | {cal} | {rel} | "
                 f"{topo} | {spec} | `{gg}` | `{rid}` |")
    n_rows_total += len(rows)
    L.append("")
L.append("*Scores from different suite versions are NOT comparable — never merge boards.*")
L.append("")

# ---- quarantined runs: visible, never ranked ----
if quarantine_list:
    L.append("## ⚠️ Quarantined runs (degenerate score patterns — NOT ranked)")
    L.append("")
    L.append("| run_id | reason |")
    L.append("|---|---|")
    for rid, why in sorted(quarantine_list):
        L.append(f"| `{rid}` | {why} |")
    L.append("")
    L.append("*Flat or near-dead domain scores are a harness symptom (wrong tool parser,")
    L.append("grader bug) until a human verifies the model really behaves this way.*")
    L.append("")

# ---- throughput board ----
L.append("## Serving throughput (tier2, measured)")
L.append("")
L.append("| Model / config | Single-stream tok/s | Aggregate tok/s (rising concurrency) | Spec | run_id |")
L.append("|---|---|---|---|---|")
for b, rid in sorted(latest.items()):
    run = runs[rid]
    if not run["has_eval"] and (run["ss"] or run["agg"]):
        ss = " / ".join(f"{v:.1f}" for v in sorted(run["ss"])) or "—"
        agg = " → ".join(f"{v:.0f}" for v in sorted(run["agg"])) or "—"
        L.append(f"| {model_of(b)} | {ss} | {agg} | {run['spec']} | `{rid}` |")
L.append("")

# ---- older suites pointer ----
n_other = sum(1 for b, rid in latest.items()
              if runs[rid]["has_eval"] and "truescore" in runs[rid]["metrics"]
              and ver_key(suite_of(b)) < (6, 0, ""))
L.append(f"*{n_other} runs from earlier suites (v2/v5c…) are in the CSV — v5-era agentic "
         f"grading is known-broken (uniform ~5.3 artifact); do not cite those agentic numbers.*")
L.append("")
L.append("Source: `~/projects/spark-bench/results/spark_bench.csv` · Renderer: `render_leaderboard.py`")
L.append("")

with open(OUT, "w") as f:
    f.write("\n".join(L))
print(f"wrote {OUT}: {n_rows_total} ranked rows across {len(by_suite)} suite boards, "
      f"{len(quarantine_list)} quarantined")
