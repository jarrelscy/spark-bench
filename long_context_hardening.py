def _unique_object(pairs):
    obj = {}
    for key, value in pairs:
        if key in obj:
            raise ValueError('duplicate JSON key')
        obj[key] = value
    return obj


def _reject_constant(value):
    raise ValueError('non-finite JSON constant')


def grade(response):
    """Exact relationships/citations; partial diagnostics never qualify a pass."""
    if not isinstance(response, dict) or response.get('finish', 'stop') != 'stop':
        return 0.0, 'LC-03: missing response or nonterminal finish'
    text = response.get('text')
    if not isinstance(text, str):
        return 0.0, 'LC-03: text must be raw JSON'
    try:
        obj = json.loads(text, object_pairs_hook=_unique_object, parse_constant=_reject_constant)
    except (ValueError, TypeError, RecursionError):
        return 0.0, 'LC-03: invalid, duplicate-key, or non-finite JSON'
    if (not isinstance(obj, dict) or set(obj) != {'as_of', 'answers'}
            or obj['as_of'] != AS_OF or not isinstance(obj['answers'], list)
            or len(obj['answers']) != len(EXPECTED)):
        return 0.0, 'LC-03: wrong root contract, cutoff, or answer count'
    checks = []
    for actual, expected in zip(obj['answers'], EXPECTED):
        if not isinstance(actual, dict) or set(actual) != set(expected):
            return 0.0, 'LC-03: wrong answer keys'
        for field, wanted in expected.items():
            value = actual[field]
            if field == 'evidence':
                ok = (isinstance(value, list) and all(isinstance(v, str) for v in value)
                      and len(value) == len(wanted) and set(value) == set(wanted))
            else:
                ok = type(value) is type(wanted) and value == wanted
            checks.append((f"{expected['ticket_id']}.{field}", ok))
    failed = [name for name, ok in checks if not ok]
    strict = not failed
    score = 1.0 if strict else 0.49 * sum(ok for _, ok in checks) / len(checks)
    return score, (f'LC-03 strict_success={str(strict).lower()}; '
                   f'{sum(ok for _, ok in checks)}/{len(checks)} fields; '
                   + ('all relationships and citations correct' if strict else 'failed: ' + ', '.join(failed)))
