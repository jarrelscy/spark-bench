def _ticket(account):
    return dict(kind='ticket', account_id=account, service='vault')


def _account(account, name, region):
    return dict(kind='account', account_id=account, display_name=name, region=region)


def _binding(region, policy):
    return dict(kind='binding', region=region, service='vault', policy_id=policy)


def _policy(policy, revision, start, route, days, end=None):
    return dict(kind='policy_revision', policy_id=policy, revision=revision,
                effective_from=start, effective_until=end, route=route,
                retention_days=days)


def _decision(policy, revision, region, issued, decision='approved'):
    return dict(kind='decision', policy_id=policy, revision=revision,
                region=region, service='vault', issued_at=issued, decision=decision)


